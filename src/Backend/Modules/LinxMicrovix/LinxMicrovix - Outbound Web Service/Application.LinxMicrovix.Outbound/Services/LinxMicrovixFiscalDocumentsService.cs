                        var batchTime = _linxMicrovixService.GetBatchTime();

                        var _listSomenteNovos = new List<Domain.LinxMicrovix.Outbound.Entities.Reads.Erp.FiscalDocuments.LinxNFeEvento>();
                        var records = new Dictionary<string, string>();

