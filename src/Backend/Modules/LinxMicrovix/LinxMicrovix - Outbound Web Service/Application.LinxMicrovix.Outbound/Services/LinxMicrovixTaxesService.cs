        public async Task<bool?> LinxNaturezaOperacao()
        {
            _logger
                .Clear()
                .AddLog(EnumJob.LinxNaturezaOperacao);

            var totalInseridos = 0;

            try
            {
                foreach (var company in await _linxMicrovixService.GetCompanys())
                {
                    if (company.erp_chave is null)
                        continue;   // cliente sem o WS de saída padrão

                    var stores = await _linxMicrovixService.GetStores(company, EnumApi.Erp);

                    if (stores.Count == 0)
                    {
                        _logger.AddMessage($"Empresa {company.doc_company} sem lojas em linxmicrovix.LinxGrupoLojas: rode o LinxGrupoLojas antes.");
                        continue;
                    }

                    // a resposta não identifica a loja: o dado é do portal, lido pela primeira loja
                    foreach (var cnpj_emp in stores.Take(1))
                    {
                        // timestamp exclusivo: a API devolve só os maiores que o informado; banco vazio (0) traz o histórico inteiro
                        var timestamp = await _linxMicrovixService.GetLastTimestamp(company, EnumJob.LinxNaturezaOperacao, null);
                        var rows = new List<(Domain.LinxMicrovix.Outbound.Dtos.Reads.Erp.Taxes.LinxNaturezaOperacao dto, string xml)>();
                        var failed = false;

                        for (var page = 1; page <= MaxPages; page++)
                        {
                            var requestBody = new XDocument(
                                new XDeclaration("1.0", "utf-8", null),
                                new XElement("LinxMicrovix",
                                    new XElement("Authentication", new XAttribute("user", company.erp_user_name ?? String.Empty), new XAttribute("password", company.erp_password ?? String.Empty)),
                                    new XElement("ResponseFormat", "xml"),
                                    new XElement("Command",
                                        new XElement("Name", "LinxNaturezaOperacao"),
                                        new XElement("Parameters",
                                            new XElement("Parameter", new XAttribute("id", "chave"), company.erp_chave),
                                            new XElement("Parameter", new XAttribute("id", "cnpjEmp"), cnpj_emp),
                                            new XElement("Parameter", new XAttribute("id", "timestamp"), timestamp)
                                        )
                                    )
                                )
                            );

                            // uma nova tentativa: 502/503/504 espera 10 s. Os erros da API chegam com HTTP 200 (testado)
                            ApiResponse? response = null;

                            for (var attempt = 1; attempt <= 2; attempt++)
                            {
                                using var content = new StringContent($"{requestBody.Declaration}{requestBody}", Encoding.UTF8, "application/xml");

                                response = await _apiClient.SendAsync(HttpMethod.Post, "LinxNaturezaOperacao", content);

                                if (attempt == 1 && response.StatusCode is 502 or 503 or 504)
                                {
                                    await Task.Delay(TimeSpan.FromSeconds(10));
                                    continue;
                                }

                                break;
                            }

                            if (response is null || !response.IsSuccess)
                            {
                                var body = response?.Content?.Length > 800 ? response.Content[..800] : response?.Content;
                                _logger.AddMessage($"Erro da API Linx Microvix em LinxNaturezaOperacao (empresa {company.doc_company}, loja {cnpj_emp}, timestamp {timestamp}): {response?.StatusCode} {body}");

                                failed = true;
                                break;
                            }

                            XElement? root = null;

                            try
                            {
                                root = XDocument.Parse(response.Content?.TrimStart('\uFEFF') ?? String.Empty).Root;
                            }
                            catch (XmlException)
                            {
                                // root continua null: tratado abaixo como resposta inválida
                            }

                            if (root is null || !String.Equals(root.Element("ResponseResult")?.Element("ResponseSuccess")?.Value, "true", StringComparison.OrdinalIgnoreCase))
                            {
                                var message = root?.Descendants("Message").FirstOrDefault()?.Value ?? (response.Content?.Length > 800 ? response.Content[..800] : response.Content);
                                _logger.AddMessage($"Resposta de erro da API Linx Microvix em LinxNaturezaOperacao (empresa {company.doc_company}, loja {cnpj_emp}, timestamp {timestamp}): {message}");

                                failed = true;
                                break;
                            }

                            var columns = root.Element("ResponseData")?.Element("C")?.Elements("D").Select(d => d.Value).ToList() ?? [];
                            var pageRows = root.Element("ResponseData")?.Elements("R").ToList() ?? [];

                            // erro de parâmetro também vem com ResponseSuccess = True: <C /> vazio e a mensagem numa linha (testado no LinxFaturas)
                            if (columns.Count == 0 && pageRows.Count > 0)
                            {
                                _logger.AddMessage($"Resposta de erro da API Linx Microvix em LinxNaturezaOperacao (empresa {company.doc_company}, loja {cnpj_emp}, timestamp {timestamp}): {pageRows[0].Value}");

                                failed = true;
                                break;
                            }

                            // resposta vazia: não há mais registros com timestamp maior que o informado
                            if (pageRows.Count == 0)
                                break;

                            foreach (var r in pageRows)
                            {
                                // <D /> é nulo; a linha é registrada em auditing.Records com o nome de cada coluna
                                var values = r.Elements("D").Select(d => d.IsEmpty ? null : d.Value).ToList();
                                var row = columns.Select((c, i) => (c, v: i < values.Count ? values[i] : null)).GroupBy(x => x.c).ToDictionary(g => g.Key, g => g.First().v);

                                rows.Add((
                                    new Domain.LinxMicrovix.Outbound.Dtos.Reads.Erp.Taxes.LinxNaturezaOperacao
                                    {
                                    portal = row.GetValueOrDefault("portal"),
                                    cod_natureza_operacao = row.GetValueOrDefault("cod_natureza_operacao"),
                                    descricao = row.GetValueOrDefault("descricao"),
                                    soma_relatorios = row.GetValueOrDefault("soma_relatorios"),
                                    operacao = row.GetValueOrDefault("operacao"),
                                    inativa = row.GetValueOrDefault("inativa"),
                                    timestamp = row.GetValueOrDefault("timestamp"),
                                    calcula_ipi = row.GetValueOrDefault("calcula_ipi"),
                                    calcula_iss = row.GetValueOrDefault("calcula_iss"),
                                    calcula_irrf = row.GetValueOrDefault("calcula_irrf"),
                                    tipo_preco = row.GetValueOrDefault("tipo_preco"),
                                    atualiza_custo = row.GetValueOrDefault("atualiza_custo"),
                                    transferencia = row.GetValueOrDefault("transferencia"),
                                    baixar_estoque = row.GetValueOrDefault("baixar_estoque"),
                                    consumo_proprio = row.GetValueOrDefault("consumo_proprio"),
                                    contabiliza_cmv = row.GetValueOrDefault("contabiliza_cmv"),
                                    despesa = row.GetValueOrDefault("despesa"),
                                    atualiza_custo_medio = row.GetValueOrDefault("atualiza_custo_medio"),
                                    exige_nf_origem = row.GetValueOrDefault("exige_nf_origem"),
                                    integra_contabilidade = row.GetValueOrDefault("integra_contabilidade"),
                                    id_obs = row.GetValueOrDefault("id_obs"),
                                    venda_futura = row.GetValueOrDefault("venda_futura"),
                                    base_icms_considera_ipi = row.GetValueOrDefault("base_icms_considera_ipi"),
                                    permite_escolha_historico = row.GetValueOrDefault("permite_escolha_historico"),
                                    import_produtos = row.GetValueOrDefault("import_produtos"),
                                    deposito_reserva_venda = row.GetValueOrDefault("deposito_reserva_venda"),
                                    exibe_nfe = row.GetValueOrDefault("exibe_nfe"),
                                    faturamento_antecipado = row.GetValueOrDefault("faturamento_antecipado"),
                                    exibir_informacoes_imposto = row.GetValueOrDefault("exibir_informacoes_imposto"),
                                    gera_garantia_nacional = row.GetValueOrDefault("gera_garantia_nacional"),
                                    transferencia_deposito = row.GetValueOrDefault("transferencia_deposito"),
                                    venda_diferencial_aliquota = row.GetValueOrDefault("venda_diferencial_aliquota"),
                                    insere_obs_pis_cofins = row.GetValueOrDefault("insere_obs_pis_cofins"),
                                    diferencial_ativo_consumo = row.GetValueOrDefault("diferencial_ativo_consumo"),
                                    recusa_de = row.GetValueOrDefault("recusa_de"),
                                    codigo_ws = row.GetValueOrDefault("codigo_ws")
                                    },
                                    new XElement("R", row.Select(x => new XElement(x.Key, x.Value))).ToString(SaveOptions.DisableFormatting)
                                ));
                            }

                            // a resposta vem em ordem crescente de timestamp (testado): a próxima página começa no maior desta
                            var lastTimestamp = rows.Max(x => MicrovixConverters.ToInt64(x.dto.timestamp));

                            if (lastTimestamp <= timestamp)
                                break;

                            timestamp = lastTimestamp;
                        }

                        // leitura incompleta não é gravada: a próxima execução sai do MAX(timestamp) e pularia o que faltou
                        if (failed || rows.Count == 0)
                            continue;

                        totalInseridos += await SaveLinxNaturezaOperacao(company.doc_company!, _linxMicrovixService.GetBatchTime(), rows);
                    }
                }

                _logger.AddMessage(
                    $"Concluída com sucesso: {totalInseridos} registro(s) novo(s) ou atualizado(s) inserido(s)!"
                );

                return true;
            }
            finally
            {
                _logger.SetLogEndDate();
                await _logger.CommitAllChanges();
            }
        }

